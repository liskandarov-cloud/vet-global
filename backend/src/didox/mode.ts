// Режим ЭДО (Didox) и подписи E-IMZO.
//
// Имитация «отправляла» и «подписывала» счёт-фактуру, которой нет, и стояла на
// проде: продавец видел подписанный налоговый документ. Теперь она только рядом
// с вымышленными данными (SEED_DEMO=true). С токеном Didox — настоящий обмен;
// без токена и без демо-данных ЭДО выключено и об этом говорится прямо.
export type DidoxMode = 'live' | 'demo' | 'off';

export function didoxMode(get: (key: string) => string | undefined): DidoxMode {
  if (get('DIDOX_TOKEN')) return 'live';
  return get('SEED_DEMO') === 'true' ? 'demo' : 'off';
}

