// Номер счёта для заказа.
//
// Формула жила двумя независимыми копиями — в orders.service при выдаче PDF и в
// didox.service при отправке в ЭДО. Обе собирали номер одинаково, но раздельно,
// и расхождение означало бы, что номер в PDF не совпадает с номером документа в
// ЭДО. Это юридически значимые документы, и такое расхождение пришлось бы
// разбирать вручную по каждой сделке.

// Столько шестнадцатеричных знаков идентификатора берётся в номер. Восемь дают
// 4 млрд значений: для номера, который показывается человеку, это компромисс
// между читаемостью и различимостью.
const ID_CHARS = 8;

export function invoiceNumberFor(order: { id: string; createdAt: Date }): string {
  return `VG-${order.createdAt.getFullYear()}-${order.id.slice(0, ID_CHARS).toUpperCase()}`;
}
