// Срок жизни токена из переменной окружения.
//
// Библиотека подписи принимает либо число секунд, либо строку вида «7d». Раньше
// значение уходило туда как есть: опечатка в переменной («7дней», «7 d») не
// мешала приложению подняться, а падала при первой же попытке входа — то есть
// на проде, у первого пользователя, и выглядела как «сайт не пускает».
//
// Теперь значение проверяется на старте: неверное останавливает запуск, и
// ошибку видно в логе выкатки, а не в жалобе клиента.

// Единицы, которые понимает библиотека: секунды, минуты, часы, дни, недели, годы.
const UNIT = /^(\d+)\s*(s|m|h|d|w|y)$/i;

export function parseJwtExpiry(raw: string | undefined, fallback = '7d'): string | number {
  const value = (raw ?? '').trim() || fallback;

  // Чистое число — это секунды.
  if (/^\d+$/.test(value)) {
    const seconds = Number(value);
    if (seconds > 0) return seconds;
    throw new Error(`JWT_EXPIRES_IN=${raw}: срок жизни токена должен быть больше нуля`);
  }

  const m = UNIT.exec(value);
  if (!m || Number(m[1]) <= 0) {
    throw new Error(
      `JWT_EXPIRES_IN=${raw}: ожидается число секунд или строка вида «30m», «12h», «7d» (s, m, h, d, w, y)`,
    );
  }
  // Пробелы внутри библиотека тоже понимает не всегда — отдаём канонический вид.
  return `${Number(m[1])}${m[2].toLowerCase()}`;
}
