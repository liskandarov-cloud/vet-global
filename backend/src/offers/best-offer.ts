import { packPriceOf } from '../common/pricing';

// Какое предложение получит покупатель, если не выбрал продавца сам.
//
// Одно правило для карточки и для заказа: в наличии — самое дешёвое с учётом
// фасовки; если в наличии нет ни одного — самое дешёвое из «под заказ».
//
// Раньше заказ искал только среди предложений в наличии, а не найдя, молча
// уходил в старую ветку цены карточки, где наличие не проверяется: товар,
// которого нет ни у одного продавца, оформлялся как обычная покупка с оплатой
// сразу. Теперь это предзаказ — оплата после подтверждения продавцом, как и
// задумано для «под заказ».
export function pickBestOffer<T extends { inStock: boolean }>(offers: T[]): T | null {
  let best: T | null = null;
  for (const o of offers) {
    if (
      !best ||
      (o.inStock && !best.inStock) ||
      (o.inStock === best.inStock && packPriceOf(o) < packPriceOf(best))
    ) {
      best = o;
    }
  }
  return best;
}
