// Применение миграций при старте — с приёмом уже существующей базы.
//
// Раньше схема применялась командой `prisma db push --accept-data-loss` при
// каждом старте контейнера: Prisma подгоняла базу под код сама, и флаг разрешал
// ей удалять то, что мешает. Пока схему меняли аккуратно, это проходило, но
// однажды такое молча снесло бы колонку с боевыми данными — без записи о том,
// что произошло, и без возможности повторить то же самое на другом контуре.
//
// Теперь изменения едут миграциями. Разница принципиальная: миграция — это
// зафиксированный в репозитории SQL, который применяется один раз и в том же
// порядке везде; `migrate deploy` никогда не удаляет то, о чём не сказано в
// самой миграции, а при расхождении отказывается работать вместо того, чтобы
// «починить» базу по-своему.
//
// Сложность одна: боевая база уже существует и создана прежним способом, то
// есть таблицы в ней есть, а журнала миграций нет. Для такой базы первая
// миграция помечается применённой (baseline) — иначе `migrate deploy` попробует
// создать существующие таблицы и упадёт.

import { PrismaClient } from '@prisma/client';
import { execFileSync } from 'child_process';

// Имя первой миграции: она описывает схему целиком на момент перехода.
const BASELINE = '0_init';

// Таблица, по которой видно, что база не пустая. Подошла бы любая из давно
// существующих; User есть с первого дня проекта.
const KNOWN_TABLE = 'public."User"';

function prisma(...args: string[]) {
  execFileSync('npx', ['prisma', ...args], { stdio: 'inherit' });
}

async function main() {
  const db = new PrismaClient();
  try {
    const [{ has_journal, has_tables }] = await db.$queryRawUnsafe<
      { has_journal: boolean; has_tables: boolean }[]
    >(
      `SELECT to_regclass('public._prisma_migrations') IS NOT NULL AS has_journal,
              to_regclass('${KNOWN_TABLE}') IS NOT NULL AS has_tables`,
    );

    if (!has_journal && has_tables) {
      // База создана прежним способом: таблицы есть, журнала нет. Помечаем
      // первую миграцию применённой, не выполняя её SQL.
      console.log(`[migrate] база существует без журнала миграций — принимаю её как ${BASELINE}`);
      prisma('migrate', 'resolve', '--applied', BASELINE);
    } else if (!has_journal) {
      console.log('[migrate] база пустая — миграции создадут схему с нуля');
    }
  } finally {
    await db.$disconnect();
  }

  prisma('migrate', 'deploy');
}

main().catch((err) => {
  // Падение здесь обязано останавливать запуск: приложение на несовпадающей
  // схеме отвечает 500 на случайных запросах, и это хуже, чем неподнявшийся
  // контейнер, при котором продолжает работать предыдущий.
  console.error('[migrate] не удалось применить миграции:', err);
  process.exit(1);
});
