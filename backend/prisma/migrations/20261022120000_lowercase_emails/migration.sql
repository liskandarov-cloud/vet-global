-- Почта сравнивается без учёта регистра: приложение теперь приводит её к
-- нижнему регистру при регистрации и входе. Существующие записи приводятся
-- здесь же, иначе пользователь «Farm@mail.uz» перестал бы входить вовсе.
--
-- Адрес, у которого уже есть двойник другим регистром, не трогаем: приведение
-- нарушило бы уникальность, и миграция остановила бы выкатку. Такие двойники —
-- это два разных аккаунта, и решать, какой из них оставить, должен человек.
UPDATE "User" AS u
SET "email" = lower(trim(u."email"))
WHERE u."email" <> lower(trim(u."email"))
  AND NOT EXISTS (
    SELECT 1
    FROM "User" AS other
    WHERE other."id" <> u."id"
      AND lower(trim(other."email")) = lower(trim(u."email"))
  );
