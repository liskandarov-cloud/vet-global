// Плоский конфиг ESLint.
//
// В Next 16 eslint-config-next сам отдаёт плоские конфиги массивом, поэтому
// прослойка FlatCompat не нужна — при попытке обернуть его ESLint падает на
// «Converting circular structure to JSON». В Next 15 она, наоборот, требовалась.
import coreWebVitals from 'eslint-config-next/core-web-vitals';

const config = [
  {
    ignores: ['.next/**', '.open-next/**', 'node_modules/**', 'next-env.d.ts'],
  },
  ...coreWebVitals,
  {
    rules: {
      // Понижено до предупреждения осознанно, а не чтобы спрятать.
      //
      // Правило появилось в Next 16 и считает ошибкой любой setState внутри
      // эффекта. Часть наших случаев — именно тот приём, который для SSR
      // правилен: ThemeToggle читает класс темы с documentElement, который
      // ставится скриптом до гидратации. Прочитать его во время рендера нельзя
      // — сервер и клиент разойдутся, и React выбросит ошибку гидратации.
      // То же у переключателя языка: значение лежит в localStorage, которого на
      // сервере нет.
      //
      // Остальные шесть разобраны поимённо и оставлены осознанно:
      //
      //   catalog:72 — setLoading(true) в начале запроса, ровно для этого и нужен;
      //   products:67 — setStockSub(false) присваивает примитив, React такую
      //     перерисовку пропускает сам;
      //   products:103 и SearchBox:32 — сброс в пустой объект и пустой массив при
      //     отсутствии данных; создают новое значение каждый прогон, то есть дают
      //     лишнюю перерисовку, но поведение верное, а переписывание на
      //     производное состояние заметно усложнило бы чтение.
      //
      // Сброс страницы в каталоге и потерянная зависимость load в заказах и
      // тендерах были настоящими и исправлены: первый перенесён в рендер, вторые
      // обёрнуты в useCallback.
      'react-hooks/set-state-in-effect': 'warn',
    },
  },
];

export default config;
